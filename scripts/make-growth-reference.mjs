// Builds src/domain/growthReference.ts from the WHO growth standards (birth to 24 months) as published by the CDC:
// https://www.cdc.gov/growthcharts/who-data-files.htm
// Usage: node scripts/make-growth-reference.mjs <folder with the six WHO-*-for-age-Percentiles CSV files>
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) {
  console.error('Usage: node scripts/make-growth-reference.mjs <folder with the WHO CSV files>')
  process.exit(1)
}

const MEASURES = [
  ['weight', /Weight-for-age/i],
  ['length', /Length-for-age/i],
  ['head', /Head-Circumference-for-age/i],
]
const files = readdirSync(dir).filter((f) => f.endsWith('.csv'))
const rows = []
for (const sex of ['boy', 'girl']) {
  for (const [measure, pattern] of MEASURES) {
    const matches = files.filter((f) => pattern.test(f) && f.toLowerCase().includes(sex === 'boy' ? 'boys' : 'girls'))
    if (matches.length !== 1) throw new Error(`Expected one ${sex} ${measure} file in ${dir}, found ${matches.length}`)
    const lines = readFileSync(join(dir, matches[0]), 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/)
    const header = lines[0].split(',')
    if (header[0] !== 'Month' || header[1] !== 'L' || header[2] !== 'M' || header[3] !== 'S') throw new Error(`Unexpected columns in ${matches[0]}`)
    for (const line of lines.slice(1)) {
      const [month, l, m, s] = line.split(',').map(Number)
      if ([month, l, m, s].some((n) => !Number.isFinite(n))) throw new Error(`Bad row in ${matches[0]}: ${line}`)
      rows.push([sex, measure, month, l, m, s])
    }
  }
}

const body = rows.map((r) => `  ['${r[0]}', '${r[1]}', ${r[2]}, ${r[3]}, ${r[4]}, ${r[5]}],`).join('\n')
writeFileSync(
  new URL('../src/domain/growthReference.ts', import.meta.url),
  `// Generated by scripts/make-growth-reference.mjs from the WHO Child Growth Standards (birth to 24 months, as published
// by the CDC at https://www.cdc.gov/growthcharts/who-data-files.htm). Do not edit by hand.
// Weight is in kilograms, length and head circumference in centimetres. L, M and S are the WHO LMS parameters.
export type Sex = 'boy' | 'girl'
export type GrowthKind = 'weight' | 'length' | 'head'
export type GrowthRef = [sex: Sex, kind: GrowthKind, month: number, l: number, m: number, s: number]

export const WHO_GROWTH_REFERENCE: GrowthRef[] = [
${body}
]
`,
)
console.log(`Wrote ${rows.length} rows`)
